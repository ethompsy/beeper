def upsert_knowledge_entries(client: QdrantClient) -> int:
    """Upsert sample runbook entries into the knowledge collection.

    Returns the number of entries upserted.
    """
    points = []
    for runbook in SAMPLE_RUNBOOKS:
        point = PointStruct(
            id=str(uuid.uuid5(uuid.NAMESPACE_DNS, runbook["entry_id"])),
            vector=generate_placeholder_embedding(runbook["entry_id"]),
            payload={
                "entry_id": runbook["entry_id"],
                "entry_type": runbook["entry_type"],
                "title": runbook["title"],
                "content": runbook["content"],
                "service": runbook["service"],
                "created_at": runbook["created_at"],
            },
        )
        points.append(point)
        logger.info(f"  Prepared runbook: {runbook['title']}")

    client.upsert(collection_name="knowledge", points=points, wait=True)
    return len(points)


def upsert_investigation_entries(client: QdrantClient) -> int:
    """Upsert sample investigation entries into the investigations collection.

    Returns the number of entries upserted.
    """
    points = []
    for inv in SAMPLE_INVESTIGATIONS:
        point = PointStruct(
            id=str(uuid.uuid5(uuid.NAMESPACE_DNS, inv["investigation_id"])),
            vector=generate_placeholder_embedding(inv["investigation_id"]),
            payload={
                "investigation_id": inv["investigation_id"],
                "status": inv["status"],
                "service": inv["service"],
                "started_at": inv["started_at"],
                "title": inv["title"],
                "root_cause": inv["root_cause"],
                "resolution": inv["resolution"],
            },
        )
        points.append(point)
        logger.info(f"  Prepared investigation: {inv['title']}")

    client.upsert(collection_name="investigations", points=points, wait=True)
    return len(points)


def main() -> int:
    """Main entry point."""
    parser = argparse.ArgumentParser(
        description="Seed Qdrant with sample KB entries for development"
    )
    parser.add_argument(
        "--host",
        default=os.getenv("QDRANT_HOST", "localhost"),
        help="Qdrant server host (default: localhost)",
    )
    parser.add_argument(
        "--port",
        type=int,
        default=int(os.getenv("QDRANT_PORT", "6333")),
        help="Qdrant server port (default: 6333)",
    )
    args = parser.parse_args()

    logger.info(f"Connecting to Qdrant at {args.host}:{args.port}")

    try:
        client = QdrantClient(host=args.host, port=args.port)
        client.get_collections()
        logger.info("Connected to Qdrant successfully")
    except Exception as e:
        logger.error(f"Failed to connect to Qdrant: {e}")
        return 1

    # Seed knowledge collection (runbooks)
    logger.info("Seeding knowledge collection with runbooks...")
    try:
        kb_count = upsert_knowledge_entries(client)
        logger.info(f"Upserted {kb_count} runbook entries")
    except Exception as e:
        logger.error(f"Failed to seed knowledge collection: {e}")
        return 1

    # Seed investigations collection
    logger.info("Seeding investigations collection with sample data...")
    try:
        inv_count = upsert_investigation_entries(client)
        logger.info(f"Upserted {inv_count} investigation entries")
    except Exception as e:
        logger.error(f"Failed to seed investigations collection: {e}")
        return 1

    logger.info(f"Seeding complete! Total entries: {kb_count + inv_count}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
