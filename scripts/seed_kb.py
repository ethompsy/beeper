"""Seed Qdrant with sample KB entries for local development.

This script populates the 'knowledge' and 'investigations' collections
with sample data for testing and development purposes.

Usage:
    python scripts/seed_kb.py [--host HOST] [--port PORT]

Environment variables:
    QDRANT_HOST: Qdrant server host (default: localhost)
    QDRANT_PORT: Qdrant server port (default: 6333)
"""

